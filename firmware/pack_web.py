def inline_page(html_path):
    """Inline local <link rel=stylesheet> and <script src> files so the page is one file."""
    import re
    base=html_path.parent
    text=html_path.read_text(encoding='utf-8')
    def css(m):
        return '<style>\n'+(base/m.group(1)).read_text(encoding='utf-8')+'\n</style>'
    def js(m):
        code=(base/m.group(1)).read_text(encoding='utf-8')
        if '</script' in code.lower():
            raise RuntimeError(m.group(1)+' contains </script')
        return '<script>\n'+code+'\n</script>'
    text=re.sub(r'<link rel="stylesheet" href="([^":]+)">',css,text)
    text=re.sub(r'<script src="([^":]+)"></script>',js,text)
    return text

def c_array(symbol,payload):
    rows=[','.join(str(b) for b in payload[i:i+24]) for i in range(0,len(payload),24)]
    return ('const uint8_t '+symbol+'[] PROGMEM = {\n'+',\n'.join(rows)+'\n};\n'
            'const size_t '+symbol+'_LEN = '+str(len(payload))+';\n')

if env.get('PIOENV') == 'six_leg_setup':
    # Phone deck: firmware/deck (plain HTML/CSS/JS). Embedded at build time.
    deck=root/'deck'
    out=['#pragma once\n#include <Arduino.h>\n// Generated by pack_web.py from firmware/deck. Do not edit.\n']
    for name,symbol in [('index.html','DECK_PAGE'),('calibration.html','CALIBRATION_PAGE')]:
        page=inline_page(deck/name)
        out.append(c_array(symbol,gzip.compress(page.encode('utf-8'),mtime=0)))
    out.append(c_array('MANIFEST_JSON',gzip.compress((deck/'manifest.webmanifest').read_bytes(),mtime=0)))
    for name,symbol in [('icon-192.png','ICON_192'),('icon-512.png','ICON_512'),('apple-touch-icon.png','ICON_180')]:
        out.append(c_array(symbol,(deck/'icons'/name).read_bytes()))
    (root/'src'/'web_assets.h').write_text('\n'.join(out),encoding='utf-8')

if sys.platform == 'win32':
    def shorten_paths(build_env, node):
        paths=[]
        seen=set()
        for value in build_env.get('CPPPATH',[]):
            path=build_env.subst(str(value))
            buffer=ctypes.create_unicode_buffer(32768)
            size=ctypes.windll.kernel32.GetShortPathNameW(path,buffer,len(buffer))
            short=buffer.value if size else str(value)
            key=short.replace('\\','/').lower()
            if key not in seen:
                paths.append(short)
                seen.add(key)
        # Build this node with a local override; mutating the shared environment
        # would make PlatformIO append duplicate long SDK paths later.
        return build_env.Object(node, CPPPATH=paths)
    env.AddBuildMiddleware(shorten_paths)
